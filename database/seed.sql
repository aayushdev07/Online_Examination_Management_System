-- -----------------------------------------------------------------------------
-- Assign questions to exams (order follows question_id; marks copied from the
-- bank). Each insert fires trg_exam_question_after_insert -> total_marks.
-- -----------------------------------------------------------------------------
INSERT INTO exam_question (exam_id, question_id, question_order, marks_assigned)
SELECT CASE
         WHEN question_id BETWEEN  1 AND 10 THEN 1
         WHEN question_id BETWEEN 11 AND 18 THEN 2
         WHEN question_id BETWEEN 19 AND 26 THEN 3
         WHEN question_id BETWEEN 27 AND 32 THEN 4
         WHEN question_id BETWEEN 33 AND 40 THEN 5
         WHEN question_id BETWEEN 41 AND 46 THEN 6
         WHEN question_id BETWEEN 47 AND 52 THEN 7
         ELSE 8
       END AS exam_id,
       question_id,
       ROW_NUMBER() OVER (PARTITION BY
         CASE
           WHEN question_id BETWEEN  1 AND 10 THEN 1
           WHEN question_id BETWEEN 11 AND 18 THEN 2
           WHEN question_id BETWEEN 19 AND 26 THEN 3
           WHEN question_id BETWEEN 27 AND 32 THEN 4
           WHEN question_id BETWEEN 33 AND 40 THEN 5
           WHEN question_id BETWEEN 41 AND 46 THEN 6
           WHEN question_id BETWEEN 47 AND 52 THEN 7
           ELSE 8
         END ORDER BY question_id) AS question_order,
       marks
  FROM question
 WHERE question_id <= 55;

